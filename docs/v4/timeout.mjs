import { chromium } from '@playwright/test';
const b = await chromium.launch({ channel: 'msedge' });
const c = await b.newContext({ viewport: { width: 1440, height: 810 } });
const p = await c.newPage();
const errs = [];
p.on('pageerror', e => errs.push(e.message));
await p.goto('http://localhost:4174/?idle=3000', { waitUntil: 'networkidle' });
await p.waitForTimeout(800);
await p.getByRole('button', { name: '打开校园来信' }).click();
await p.waitForFunction(() => document.querySelector('.v4')?.getAttribute('data-phase') === 'DISCOVER', null, { timeout: 12000 });
await p.waitForTimeout(900);
await p.evaluate(() => document.querySelector('.fan-card')?.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true })));
await p.waitForTimeout(4200);
const open = await p.evaluate(() => !!document.querySelector('dialog.v4-dialog')?.open);
console.log('dialog open after idle', open);
await p.screenshot({ path: 'docs/v4/shots/timeout-dialog.png' });
await p.getByRole('button', { name: /继续探索/ }).click();
await p.waitForTimeout(600);
console.log('dialog after resume', await p.evaluate(() => !!document.querySelector('dialog.v4-dialog')?.open), 'phase', await p.getAttribute('.v4', 'data-phase'));
await p.waitForTimeout(20000);
console.log('phase after countdown', await p.getAttribute('.v4', 'data-phase'));
await p.screenshot({ path: 'docs/v4/shots/timeout-reset.png' });
console.log('errors', JSON.stringify(errs));
await b.close();
